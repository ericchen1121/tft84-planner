import assert from 'node:assert/strict';
import fs from 'node:fs';
import {applyAugmentTags} from './augment-tagging.mjs';
import {AUGMENT_TAGS,filterAugments,augmentTagLabel} from '../src/augment-model.mjs';
const read=p=>JSON.parse(fs.readFileSync(new URL('../'+p,import.meta.url),'utf8'));
const source=read('dist/augments.json'),catalog=read('dist/augment-tags.json');
const before=JSON.stringify(source),tagged=applyAugmentTags(source,catalog),rows=tagged.augments;
assert.equal(JSON.stringify(source),before,'Tag application must not mutate the source snapshot');
assert.equal(rows.length,372);assert(rows.every(a=>a.tags.length));
assert.equal(new Set(AUGMENT_TAGS.map(t=>t.color)).size,10);
const named=name=>rows.find(a=>a.name===name);
const expectTags=(name,ids)=>{for(const id of ids)assert(named(name).tags.includes(id),name+' requires '+id);};
expectTags('Arcanist Crown',['equipment','trait','units']);
assert.deepEqual(named('Arcanist Crown').tag_details.equipment,['completed','emblem']);
expectTags('Arcanist Circlet',['equipment','trait','units']);
assert.deepEqual(named('Arcanist Circlet').tag_details.equipment,['component','emblem']);
expectTags('All That Shimmers',['equipment','economy']);
assert.deepEqual(named('All That Shimmers').tag_details.equipment,['artifact','utility']);
assert.deepEqual(named('Chalice of Power').tag_details.equipment,['support']);
assert.deepEqual(named('Radiant Relics').tag_details.equipment,['radiant','utility']);
expectTags('The Golden Egg',['growth','economy','strategy']);
expectTags('Clear Mind',['economy','growth','strategy']);
expectTags('Max Build',['economy','growth','units']);
expectTags('Tank Apprentice',['equipment','growth']);
assert(named('Clear Mind').tag_details.economy.includes('xp'));
assert(!named('Ascension').tags.includes('growth'),'In-combat timer is not a later-round reward');
assert(!named('Prismatic Destiny').tags.includes('prismatic-cap'),'Augment rarity is not a Prismatic trait quest');
assert(!named('Arcanist Crown').tags.includes('prismatic-cap'),'An emblem alone does not grant the Prismatic quest');
assert(!named('Heroic Grab Bag').tags.includes('hero'),'Duplicators do not modify champion abilities');
assert(!named('Heroic Grab Bag').tags.includes('equipment'),'Champion duplicators are champion resources, not equipment');
assert(!named('Item Grab Bag').tags.includes('combat'),'An ordinary item grant is not automatically a stat augment');
assert.equal(rows.filter(a=>a.tags.includes('hero')).length,7);
assert.equal(rows.filter(a=>a.tags.includes('prismatic-cap')).length,9);
expectTags('K/DA Prismatic Tour',['trait','strategy','growth','prismatic-cap','units','economy']);
assert(!named('K/DA Prismatic Tour').tags.includes('equipment'),'Duplicator-only quest is not an equipment grant');
assert(!named('Counting Stars'));assert(!named('Hard Commit'));
const any=filterAugments(rows,{tags:['hero','prismatic-cap']}),all=filterAugments(rows,{tags:['equipment','growth'],tagMode:'all'});
assert.equal(any.length,16);assert(all.length>0);assert(all.every(a=>a.tags.includes('equipment')&&a.tags.includes('growth')));
assert.equal(filterAugments(rows,{tags:['hero','prismatic-cap'],tagMode:'all'}).length,0);
assert(filterAugments(rows,{equipment:'artifact',tags:['growth'],tagMode:'all'}).some(a=>a.name==='Latent Forge'));
assert(filterAugments(rows,{query:'角色強化',tier:'Silver',round:'2-1'}).length>0);
assert(filterAugments(rows,{query:'radiant items',tags:['equipment'],equipment:'radiant'}).every(a=>a.tag_details.equipment.includes('radiant')));
assert.equal(augmentTagLabel(AUGMENT_TAGS[0],'en'),'Equipment');assert.equal(augmentTagLabel(AUGMENT_TAGS[0],'zh-Hant'),'裝備');
assert.throws(()=>applyAugmentTags({...source,set:'TFTSet20'},catalog),/mismatch/);
assert.throws(()=>applyAugmentTags({...source,augments:[{...source.augments[0],description:'Changed effect'}]},catalog),/need review/);
assert.throws(()=>applyAugmentTags({...source,augments:[{...source.augments[0],id:'unreviewed'}]},catalog),/need review/);
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const embedded=JSON.parse(html.match(/<script id="augment-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
assert.equal(embedded.augments.length,372);assert(embedded.augments.every(a=>a.tags.length));assert(html.includes('id="augment-tag-filters"'));assert(html.includes('id="augment-equipment"'));
assert(!html.includes('/*__AUGMENTS__*/'));
console.log(JSON.stringify({augment_tags:'PASS',classified:372,categories:10,hero:7,prismatic_quests:9,any_all_filter:true,equipment_subtypes:true,changed_effect_requires_review:true}));
