let currentLanguage='zh-Hant';
export function setLanguage(value){currentLanguage=value==='en'?'en':'zh-Hant';return currentLanguage;}
export function getLanguage(){return currentLanguage;}
export function t(source,params={}){
  const template=currentLanguage==='zh-Hant'?(UI_ZH[source]??source):source;
  return template.replace(/\{(\w+)\}/g,(_,key)=>String(params[key]??'{'+key+'}'));
}
export function traitLabel(name,language=currentLanguage){return language==='zh-Hant'?(TRAIT_ZH[name]??name):name;}
export function traitSearchText(names){return names.map(name=>name+' '+(TRAIT_ZH[name]||'')).join(' ');}
export function localizedStaticText(source){
  const trimmed=source.trim();if(!trimmed)return source;
  let text=t(trimmed);
  if(currentLanguage==='zh-Hant')for(const [name,label]of Object.entries(TRAIT_ZH).sort((a,b)=>b[0].length-a[0].length))text=text.replaceAll(name,label);
  return source.replace(trimmed,text);
}
